#!/usr/bin/env python3
"""Imports the iOS asset catalog into the Android app.

Usage: tools/import_ios_assets.py "<.../Top Gun/Assets.xcassets>" app/src/main
  png/jpg/jpeg imagesets -> res/drawable-nodpi/<name>.<ext>   (largest scale)
  pdf imagesets          -> rendered to png (pdftoppm) in res/drawable-nodpi
  svg imagesets          -> assets/svg/<name>.svg  (Coil SvgDecoder: file:///android_asset/svg/<name>.svg)
Names: imageset name lowercased, non [a-z0-9] -> '_', prefixed 'img_' if it starts with a digit; collisions get the
parent folder as a prefix. Writes docs/assets-index.md (iOS path -> Android name) and
app/src/main/java/app/topgun/android/designsystem/AssetIndex.kt (names of the svg assets).
Colorsets are NOT imported (their values are in TGColors.kt).
"""
import json, os, re, shutil, subprocess, sys

src, out = sys.argv[1], sys.argv[2]
drawable = os.path.join(out, "res", "drawable-nodpi")
svgdir = os.path.join(out, "assets", "svg")
for d in (drawable, svgdir):
    shutil.rmtree(d, ignore_errors=True); os.makedirs(d)

def sanitize(s):
    n = re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_") or "img"
    return "img_" + n if n[0].isdigit() else n

used, rows, svgs = {}, [], []
for root, dirs, files in sorted(os.walk(src)):
    if not root.endswith(".imageset"):
        continue
    rel = os.path.relpath(root, src)
    base = os.path.basename(root)[:-len(".imageset")]
    j = json.load(open(os.path.join(root, "Contents.json")))
    cands = [i for i in j["images"] if i.get("filename") and not any(a.get("value") == "dark" for a in i.get("appearances", []))]
    if not cands:
        continue
    def scale(i):
        m = re.match(r"(\d+)x", i.get("scale", "1x")); return int(m.group(1)) if m else 1
    pick = max(cands, key=scale)
    fn = pick["filename"]; ext = fn.rsplit(".", 1)[-1].lower()
    name = sanitize(base)
    if name in used:
        name = sanitize(os.path.basename(os.path.dirname(root)).replace(".imageset", "") + "_" + base)
    n = 2
    while name in used:
        name = f"{name}_{n}"; n += 1
    used[name] = rel
    path = os.path.join(root, fn)
    if ext in ("png", "jpg", "jpeg"):
        shutil.copy(path, os.path.join(drawable, f"{name}.{'jpg' if ext == 'jpeg' else ext}")); kind = "drawable"
    elif ext == "svg":
        shutil.copy(path, os.path.join(svgdir, f"{name}.svg")); kind = "svg"; svgs.append(name)
    elif ext == "pdf":
        subprocess.run(["pdftoppm", "-png", "-r", "216", "-singlefile", path, os.path.join(drawable, name)], check=True); kind = "drawable"
    else:
        continue
    rows.append((rel, kind, name))

os.makedirs("docs", exist_ok=True)
with open("docs/assets-index.md", "w") as f:
    f.write("# iOS asset -> Android name\n\n`drawable` -> `R.drawable.<name>` (`painterResource`), `svg` -> `TGAsset.svg(\"<name>\")` (Coil, assets/svg).\n\n| iOS imageset | kind | Android name |\n|---|---|---|\n")
    for rel, kind, name in rows:
        f.write(f"| `{rel}` | {kind} | `{name}` |\n")
kt = os.path.join(out, "java/app/topgun/android/designsystem/AssetIndex.kt")
with open(kt, "w") as f:
    f.write("// GENERATED by tools/import_ios_assets.py. Do not edit by hand.\npackage app.topgun.android.designsystem\n\n")
    f.write("/** Names of the SVG assets in assets/svg (country flags, icons, world map...). */\nobject TGAsset {\n")
    f.write("    val svgNames: Set<String> = setOf(\n" + "".join(f'        "{n}",\n' for n in sorted(svgs)) + "    )\n\n")
    f.write("    /** Coil model for an imported SVG: `TGAsset.svg(\"worldmap\")`. */\n    fun svg(name: String): String = \"file:///android_asset/svg/$name.svg\"\n\n")
    f.write("    /** Lowercase ISO-2 country code -> flag svg name if present (iOS `icons/Flags`). */\n    fun flagSvg(code: String?): String? =\n        code?.lowercase()?.takeIf { it in svgNames }?.let(::svg)\n}\n")
print(f"imported {len(rows)} imagesets ({len(svgs)} svg)")
