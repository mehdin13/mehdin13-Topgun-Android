#!/usr/bin/env python3
"""Generates DreamlandPalette.kt from the iOS design export's tokens.json.

Usage: tools/gen_palette.py <path to docs/design/design-pkg/ds/dreamland/tokens.json> > app/src/main/java/.../DreamlandPalette.kt
The Swift app generates its colors from the same file, so the two platforms cannot drift.
"""
import json, re, sys

THEMES = [("light", "Light"), ("dark", "Dark"), ("light-hc", "LightHighContrast"), ("dark-hc", "DarkHighContrast")]

def color(v: str) -> str:
    v = v.strip()
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})", v)
    if m:
        return f"Color(0xFF{m.group(1).upper()})"
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([0-9.]+)\)", v)
    if m:
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
        return f"Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})"
    raise SystemExit(f"unsupported color value: {v}")

def ident(name: str) -> str:
    # "brand-midnightInk" -> "brandMidnightInk"
    head, *rest = name.split("-")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)

def value(token: dict, theme: str) -> str:
    v = token["value"]
    return v[theme] if isinstance(v, dict) else v  # brand colors are the same in every theme

tokens = json.load(open(sys.argv[1]))["color"]["tokens"]
out = [
    "// GENERATED by tools/gen_palette.py from tokens.json. Do not edit by hand; regenerate.",
    "package com.mehdin13.dreamland.designsystem",
    "",
    "import androidx.compose.ui.graphics.Color",
    "",
    "/** Every color token for one theme. Names match tokens.json (and the iOS `DL.Colors`). */",
    "class DLPalette(",
]
for t in tokens:
    out.append(f"    val {ident(t['name'])}: Color,")
out.append(")")
for tid, name in THEMES:
    out += ["", f"val DL{name}Palette = DLPalette("]
    for t in tokens:
        out.append(f"    {ident(t['name'])} = {color(value(t, tid))},")
    out.append(")")
print("\n".join(out))
